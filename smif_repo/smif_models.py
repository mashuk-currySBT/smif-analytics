def factors(px, plot=True):
    """Regress each ETF on market, size, value, momentum, quality and low-vol factors built from ETF spreads."""
    r, rf = split(px)
    r = r.reindex(columns=[c for c in r.columns])
    F = pd.DataFrame(index=r.index)
    have = lambda *x: all(k in r.columns and r[k].notna().sum() > 120 for k in x)
    if have(MARKET): F["MKT"] = r[MARKET] - rf
    if have("IWM", "VOO"): F["SIZE"] = r["IWM"] - r["VOO"]
    if have("VTV", "VUG"): F["VALUE"] = r["VTV"] - r["VUG"]
    if have("MTUM", MARKET): F["MOM"] = r["MTUM"] - r[MARKET]
    if have("QUAL", MARKET): F["QUALITY"] = r["QUAL"] - r[MARKET]
    if have("USMV", MARKET): F["LOWVOL"] = r["USMV"] - r[MARKET]
    rows = {}
    for c in universe(True):
        if c not in r.columns:
            continue
        D = pd.concat([r[c] - rf, F], axis=1).dropna()
        if len(D) < 120:
            continue
        X = np.column_stack([np.ones(len(D)), D.iloc[:, 1:].values]); y = D.iloc[:, 0].values
        b, *_ = np.linalg.lstsq(X, y, rcond=None)
        res = y - X @ b
        se = np.sqrt(np.diag(np.linalg.inv(X.T @ X)) * res.var(ddof=X.shape[1]))
        rows[c] = {"alpha_ann": b[0] * TD, "alpha_t": b[0] / se[0], "R2": 1 - res.var() / y.var(),
                   **{f"b_{n}": v for n, v in zip(F.columns, b[1:])}, **{f"t_{n}": v / s for n, v, s in zip(F.columns, b[1:], se[1:])}}
    out = pd.DataFrame(rows).T
    print("=== Factor exposure (b_ = loading, t_ = t-stat; |t| > 2 is meaningful) ===")
    print(out.round(2).to_string())
    if plot and len(out):
        plt = _plt()
        B = out[[c for c in out.columns if c.startswith("b_")]].astype(float)
        B.columns = [c[2:] for c in B.columns]
        fig, ax = plt.subplots(figsize=(8, 0.45 * len(B) + 2))
        im = ax.imshow(B.values, cmap="RdBu_r", vmin=-abs(B.values).max(), vmax=abs(B.values).max(), aspect="auto"); ax.grid(False)
        ax.set_xticks(range(B.shape[1])); ax.set_xticklabels(B.columns); ax.set_yticks(range(len(B))); ax.set_yticklabels(B.index)
        for i in range(B.shape[0]):
            for j in range(B.shape[1]):
                ax.text(j, i, f"{B.values[i, j]:.2f}", ha="center", va="center", fontsize=8)
        plt.colorbar(im, shrink=.8); ax.set_title("Factor loadings")
        fig.tight_layout(); plt.show()
    return out
