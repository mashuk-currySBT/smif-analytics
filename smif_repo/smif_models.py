def _last_prices(tickers):
    import yfinance as yf
    out = {}
    for t in tickers:
        p = np.nan
        try:
            p = float(yf.Ticker(_yf(t)).fast_info["last_price"])
        except Exception:
            pass
        if not p == p:
            try:
                p = float(yf.Ticker(_yf(t)).history(period="5d")["Close"].dropna().iloc[-1])
            except Exception:
                p = np.nan
        out[t] = p
    return out


def snapshot(price_fn=None):
    """Live check: latest traded price of each ETF vs what we paid (can be ~15 min delayed)."""
    t = load_trades().set_index("etf")
    last = (price_fn or _last_prices)(list(t.index))
    d = t.copy()
    d["price_now"] = pd.Series(last)
    d["value_now"] = d.shares * d.price_now
    d["return_%"] = (d.price_now / d.price_paid - 1) * 100
    d["pnl_$"] = d.value_now - d.shares * d.price_paid
    cost = (d.shares * d.price_paid).sum()
    print(f"=== LIVE snapshot at {pd.Timestamp.now():%Y-%m-%d %H:%M} (trade date {TRADE_DATE}) ===")
    print(d[["shares", "price_paid", "price_now", "value_now", "return_%", "pnl_$"]].round(2).to_string())
    print(f"\nPORTFOLIO cost ${cost:,.2f} -> ${d.value_now.sum():,.2f}  P&L ${d.value_now.sum() - cost:,.2f} "
          f"({_pct(d.value_now.sum() / cost - 1)})")
    return d


