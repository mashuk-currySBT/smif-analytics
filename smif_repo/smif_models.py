# Day 0 = first trading day on/after the date. Students can edit/add dates. VERIFY dates before relying on them.
EVENT_GROUPS = {
    "Midterm elections (day after)": ["2006-11-08", "2010-11-03", "2014-11-05", "2018-11-07", "2022-11-09", "2026-11-04"],
    "Fed rate hikes": ["2022-03-16", "2022-06-15", "2023-07-26"],
    "Oil price spikes": ["2008-07-11", "2022-02-24", "2022-03-08"],
}


def event_study(px_all, groups=None, etfs=None, market=None, est_days=120, gap=10, pre=5, post=10, plot=True):
    """Market-model event study. For each event: fit ETF = a + b*market over est_days (ending gap days before the
       window), then abnormal return AR = actual - predicted, cumulated into CAR."""
    groups = groups or EVENT_GROUPS
    etfs = etfs or universe(True)
    market = market or MARKET
    r = px_all.drop(columns="RF", errors="ignore")[sorted(set(etfs) | {market})].pct_change()
    rows, paths = [], {}
    for g, dates in groups.items():
        for ds in dates:
            d0 = r.index.searchsorted(pd.Timestamp(ds))
            if d0 >= len(r):
                continue
            e1 = d0 - pre - gap
            e0 = e1 - est_days
            if e0 < 1:
                continue
            tau = np.arange(-pre, post + 1)
            for e in etfs:
                if e == market:
                    continue
                est = pd.concat([r[e].iloc[e0:e1], r[market].iloc[e0:e1]], axis=1).dropna()
                if len(est) < 60:
                    continue
                b, a = np.polyfit(est.iloc[:, 1], est.iloc[:, 0], 1)
                sig = (est.iloc[:, 0] - (a + b * est.iloc[:, 1])).std(ddof=2)
                ar = np.full(len(tau), np.nan)
                for k, t in enumerate(tau):
                    i = d0 + t
                    if 0 <= i < len(r) and not np.isnan(r[e].iloc[i]) and not np.isnan(r[market].iloc[i]):
                        ar[k] = r[e].iloc[i] - (a + b * r[market].iloc[i])
                paths[(g, ds, e)] = pd.Series(ar, index=tau)

                def car(t1, t2):
                    m = (tau >= t1) & (tau <= t2)
                    return (np.nan, np.nan) if np.isnan(ar[m]).any() else (ar[m].sum(), ar[m].sum() / (sig * np.sqrt(m.sum())))
                post_ar = ar[(tau >= 0) & (tau <= 5)]
                n_av = int((~np.isnan(post_ar)).sum())
                c05p = np.nansum(post_ar) if n_av else np.nan
                c01, t01 = car(0, 1)
                c05, t05 = car(0, 5)
                cm5, tm5 = car(-pre, 5)
                rows.append(dict(group=g, event=ds, etf=e, beta=b, CAR_0_1=c01 * 100, t_0_1=t01,
                                 CAR_0_5=c05 * 100, t_0_5=t05, CAR_m5_5=cm5 * 100, t_m5_5=tm5,
                                 CAR_to_date=c05p * 100, days_after=n_av))
    T = pd.DataFrame(rows)
    if T.empty:
        print("No events had enough data."); return None
    avg = T.groupby(["group", "etf"])[["CAR_0_1", "CAR_0_5", "CAR_m5_5"]].mean().round(2)
    avg["n_events"] = T.groupby(["group", "etf"]).size()
    print("=== Average abnormal return (CAR, in %) by event type. |t| > 2 on a single event is notable. ===")
    print(avg.unstack(0)["CAR_0_5"].round(2).to_string())
    print("\n(CAR_0_5 = cumulative abnormal return from event day 0 through day +5. Per-event detail is in the returned table.)")
    if plot:
        plt = _plt()
        for g in groups:
            sub = [k for k in paths if k[0] == g]
            if not sub:
                continue
            fig, ax = plt.subplots(1, 2, figsize=(13, 4.4), gridspec_kw={"width_ratios": [1.3, 1]})
            for e in [x for x in etfs if x in OWNED or len(etfs) <= 8]:
                ps = [paths[k] for k in sub if k[2] == e]
                if not ps:
                    continue
                m = pd.concat(ps, axis=1).mean(axis=1)
                ax[0].plot(m.index, m.cumsum() * 100, label=e, color=_color(e), lw=1.8)
            ax[0].axvline(0, color="k", ls="--", lw=1); ax[0].axhline(0, color="gray", lw=.8)
            ax[0].set_xlabel("trading days from the event"); ax[0].set_ylabel("average cumulative abnormal return (%)")
            ax[0].set_title(f"{g}: average over {len(groups[g])} event(s)"); ax[0].legend(ncol=3, fontsize=8)
            Tg = T[T.group == g]
            H = Tg.pivot_table(index="event", columns="etf", values="CAR_to_date")
            short = Tg.groupby("event").days_after.min()
            ylab = [e + (" *" if short.get(e, 6) < 6 else "") for e in H.index]
            im = ax[1].imshow(H.values, cmap="RdYlGn", vmin=-np.nanmax(abs(H.values)), vmax=np.nanmax(abs(H.values)), aspect="auto")
            ax[1].set_xticks(range(len(H.columns))); ax[1].set_xticklabels(H.columns, rotation=90)
            ax[1].set_yticks(range(len(H.index))); ax[1].set_yticklabels(ylab); ax[1].grid(False)
            for i in range(H.shape[0]):
                for j in range(H.shape[1]):
                    if not np.isnan(H.values[i, j]):
                        ax[1].text(j, i, f"{H.values[i, j]:.1f}", ha="center", va="center", fontsize=7)
            ax[1].set_title("CAR day 0 to +5 (%), each event  (* = window not finished yet)")
            fig.tight_layout(); plt.show()
    return T


