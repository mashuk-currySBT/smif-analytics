def top_n(etf, n=5):
    h = load_holdings()
    h = h[(h.etf == etf.upper()) & (h.ticker != "REST")]
    return h.nlargest(n, "weight_in_etf_pct")[["ticker", "name", "weight_in_etf_pct"]]


def add_holdings(etf, holdings, as_of, names=None, sectors=None, replace=True):
    """Add (or replace) an ETF's top holdings in data/holdings.csv.
       holdings = {"NVDA": 20.7, "TSM": 9.9, ...}  weights in % INSIDE the ETF. as_of = "YYYY-MM-DD"."""
    etf = etf.upper()
    tot = sum(holdings.values())
    if tot > 100.5:
        raise ValueError(f"Weights add up to {tot:.1f}%. They are % of the ETF, so they must add up to 100% or less.")
    h = load_holdings()
    if replace:
        h = h[h.etf != etf]
    rows = [dict(etf=etf, ticker=str(t).upper(), name=(names or {}).get(t, ""), sector=(sectors or {}).get(t, ""),
                 weight_in_etf_pct=float(w), source="user_input", as_of=as_of) for t, w in holdings.items()]
    rows.append(dict(etf=etf, ticker="REST", name="Rest of holdings (not listed)", sector="",
                     weight_in_etf_pct=round(100 - tot, 2), source="calculated: 100 - listed", as_of=as_of))
    h = pd.concat([h, pd.DataFrame(rows)]).sort_values(["etf", "weight_in_etf_pct"], ascending=[True, False])
    h.to_csv(os.path.join(DATA, "holdings.csv"), index=False)
    print(f"Saved {len(holdings)} holdings for {etf} (as of {as_of}); rest of fund = {100 - tot:.1f}%. "
          f"Add {etf} to sm.CANDIDATES if you want it in the models, then run sm.update().")


