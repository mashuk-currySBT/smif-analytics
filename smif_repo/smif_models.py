def walk_forward(px, tickers=None, train_yrs=2, step_m=3, plot=True):
    """Honest test: fit weights on the last N years, hold for a quarter, repeat. Compare out-of-sample."""
    tickers = tickers or universe()
    R, _, _, _ = _inputs(px, tickers)
    _, rf = split(px)
    n = len(tickers)
    b, cons, x0 = _bounds(n), {"type": "eq", "fun": lambda w: w.sum() - 1}, np.ones(n) / n
    starts = pd.date_range(R.index[0] + pd.DateOffset(years=train_yrs), R.index[-1], freq=f"{step_m}MS")
    out = {k: [] for k in ["max_sharpe", "min_variance", "equal_weight"]}
    for s in starts:
        tr = R[(R.index < s) & (R.index >= s - pd.DateOffset(years=train_yrs))]
        te = R[(R.index >= s) & (R.index < s + pd.DateOffset(months=step_m))]
        if len(te) < 5 or len(tr) < 100:
            continue
        mu, cov = tr.mean().values * TD, tr.cov().values * TD
        rfa = rf.reindex(tr.index).mean() * TD
        ws = {"max_sharpe": minimize(lambda w: -_port(w, mu, cov, rfa)[2], x0, bounds=b, constraints=cons).x,
              "min_variance": minimize(lambda w: w @ cov @ w, x0, bounds=b, constraints=cons).x, "equal_weight": x0}
        for k, w in ws.items():
            out[k].append(te @ w)
    ser = {k: pd.concat(v) for k, v in out.items() if v}
    if not ser:
        print("Window too short for a walk-forward test."); return None
    res = {k: dict(oos_return=s.mean() * TD, oos_vol=s.std() * np.sqrt(TD),
                   oos_sharpe=(s.mean() * TD - rf.mean() * TD) / (s.std() * np.sqrt(TD))) for k, s in ser.items()}
    print(f"=== Out-of-sample test ({train_yrs}-yr training window, rebalance every {step_m} months) ===")
    print(pd.DataFrame(res).T.round(3).to_string())
    if plot:
        plt = _plt()
        fig, ax = plt.subplots(figsize=(9, 4.3))
        for k, s in ser.items():
            ax.plot(s.index, np.exp(s.cumsum()), label=k, lw=1.8)
        ax.set_title("Growth of $1 using only past data to pick weights (out of sample)"); ax.legend()
        fig.tight_layout(); plt.show()
    return res


