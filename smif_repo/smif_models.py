def overall_vs_topn(px_all, n=5, weights=None, window_days=252, plot=True):
    """Whole-portfolio version: our portfolio vs a basket of every stock that is a top-N holding in any of our ETFs,
       weighted by how much of each we hold through all ETFs (look-through)."""
    w = pd.Series(weights) if weights is not None else current_weights(px_all, at="now")
    w = w / w.sum()
    names = set()
    for e in w.index:
        names |= set(top_n(e, n).ticker)
    h = load_holdings()
    h = h[(h.ticker != "REST") & h.etf.isin(w.index) & h.ticker.isin(names)].copy()
    h["exp"] = h.etf.map(w) * h.weight_in_etf_pct / 100
    expo = h.groupby("ticker").exp.sum()
    px = _window(px_all, window_days, None, None)
    bask, bw, dropped = _basket(expo.to_dict(), px)
    if dropped:
        print(f"(no price data for {dropped}; basket re-weighted over the rest)")
    cover = expo[~expo.index.isin(dropped)].sum()
    port = (px[list(w.index)].pct_change() * w).sum(axis=1, min_count=1)
    d, s, rest = _compare(port, bask, cover)
    print(f"{len(names)} stocks are a top-{n} holding in at least one of our ETFs; together they are {cover:.1%} of the portfolio.")
    lab = {"days": "days used", "coverage_pct": "% of portfolio in the basket", "correlation": "correlation",
           "R2": "R-squared", "beta_etf_on_basket": "beta of portfolio on basket",
           "tracking_error_ann_pct": "tracking error (%/yr)", "etf_return_pct": "portfolio return (%)",
           "basket_return_pct": "basket return (%)", "rest_return_pct": "everything else, implied return (%)"}
    print("\n".join(f"  {lab[k]}: {int(v) if k == 'days' else round(v, 2)}" for k, v in s.items()))
    if plot:
        _plot_compare(f"Our portfolio vs the {len(bw)} top-{n} stocks ({cover:.0%} of it)", d, rest, "our portfolio", f"top-{n} stocks")
    return s, expo.sort_values(ascending=False)


