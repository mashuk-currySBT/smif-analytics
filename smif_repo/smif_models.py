    mu, cov, rfa, tick, W = res["mu"], res["cov"], res["rfa"], res["tickers"], res["weights"]
    n = len(tick)
    rng = np.random.default_rng(0)
    Wr = rng.dirichlet(np.ones(n), 6000)
    Wr = Wr[Wr.max(axis=1) <= max(MAX_W, 1 / n + 1e-6)]
    rr, vv = Wr @ mu, np.sqrt(np.einsum("ij,jk,ik->i", Wr, cov, Wr))
    fv, fr = _frontier(mu, cov)
    plt = _plt()
    fig, ax = plt.subplots(figsize=(9.5, 6))
    sc = ax.scatter(vv * 100, rr * 100, c=(rr - rfa) / vv, s=6, cmap="viridis", alpha=.5)
