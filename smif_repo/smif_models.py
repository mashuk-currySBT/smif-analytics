def stats(px, tickers=None, show=True):
    """Annualized return, volatility, Sharpe, beta (vs MARKET), CAPM expected return, alpha, drawdown."""
    r, rf = split(px)
    tickers = tickers or universe()
    ex = r.sub(rf, axis=0)
    m = ex[MARKET]
    rows = {}
    for c in tickers:
        d = pd.concat([ex[c], m], axis=1).dropna()
        if len(d) < 60:
            continue
        beta = np.cov(d.iloc[:, 0], d.iloc[:, 1])[0, 1] / d.iloc[:, 1].var()
        ann = r[c].dropna().mean() * TD
        vol = r[c].dropna().std() * np.sqrt(TD)
        rfa = rf.mean() * TD
        capm = rfa + beta * (m.mean() * TD)
        X = np.column_stack([np.ones(len(d)), d.iloc[:, 1]])
        b, *_ = np.linalg.lstsq(X, d.iloc[:, 0].values, rcond=None)
        res = d.iloc[:, 0].values - X @ b
        se = np.sqrt(res.var(ddof=2) * np.linalg.inv(X.T @ X)[0, 0])
        cum = np.exp(r[c].dropna().cumsum())
        rows[c] = dict(days=len(d), ann_return=ann, vol=vol, sharpe=(ann - rfa) / vol, beta=beta, capm_return=capm,
                       alpha=ann - capm, alpha_tstat=b[0] / se, max_drawdown=(cum / cum.cummax() - 1).min())
    out = pd.DataFrame(rows).T
    out["days"] = out["days"].astype(int)
    if show:
        print(f"=== Risk / return / CAPM, {px.index[0].date()} to {px.index[-1].date()} (|alpha_tstat| > 2 = unlikely luck) ===")
        print(out.round(3).to_string())
        plt = _plt()
        fig, ax = plt.subplots(1, 3, figsize=(13, 3.8))
        ax[0].bar(out.index, out.sharpe, color=[_color(i) for i in out.index]); ax[0].set_title("Sharpe ratio")
        sc = ax[1]
        for i in out.index:
            sc.scatter(out.beta[i], out.ann_return[i] * 100, s=80, color=_color(i))
            sc.annotate(i, (out.beta[i], out.ann_return[i] * 100), xytext=(4, 4), textcoords="offset points")
        xs = np.linspace(min(0, out.beta.min()) - .1, out.beta.max() + .1, 20)
        rfa = rf.mean() * TD; mk = r[MARKET].mean() * TD
        sc.plot(xs, (rfa + xs * (mk - rfa)) * 100, color="gray", ls="--", label="CAPM line (security market line)")
        sc.set_xlabel("beta"); sc.set_ylabel("average return %/yr"); sc.set_title("Above the line = positive alpha")
        sc.legend(fontsize=8)
        ax[2].bar(out.index, out.alpha * 100, color=["#2e8b57" if a > 0 else "#c0392b" for a in out.alpha])
        ax[2].set_title("Alpha (% per year)")
        for i, a in zip(range(len(out)), out.alpha_tstat):
            ax[2].text(i, out.alpha.iloc[i] * 100, f"t={a:.1f}", ha="center", va="bottom", fontsize=7)
        fig.tight_layout(); plt.show()
    return out


def corr_heatmap(px, tickers=None):
    """Correlation of daily returns. The color scale shows -1 to +1 if any pair is negative."""
    r, _ = split(px)
    tickers = tickers or universe(True)
    tickers = [t for t in tickers if t in r.columns and r[t].notna().sum() > 60]
    C = r[tickers].dropna().corr()
    plt = _plt()
    lo = -1 if C.values.min() < 0 else 0
    fig, ax = plt.subplots(figsize=(0.62 * len(tickers) + 3, 0.55 * len(tickers) + 2.5))
    im = ax.imshow(C, cmap="RdYlBu_r", vmin=lo, vmax=1)
    ax.set_xticks(range(len(tickers))); ax.set_xticklabels(tickers, rotation=90)
    ax.set_yticks(range(len(tickers))); ax.set_yticklabels(tickers); ax.grid(False)
    for i in range(len(tickers)):
        for j in range(len(tickers)):
            ax.text(j, i, f"{C.iloc[i, j]:.2f}", ha="center", va="center", fontsize=7)
    plt.colorbar(im, shrink=.8); ax.set_title("Correlation of daily returns")
    fig.tight_layout(); plt.show()
    return C


def chosen_weights(tickers):
    """The weights we actually bought on the trade date (0 for ETFs we don't own)."""
    return current_weights(at="cost").reindex(tickers).fillna(0)


def _inputs(px, tickers):
    r, rf = split(px)
    missing = [t for t in tickers if t not in r.columns]
    if missing:
        raise KeyError(f"No price data for {missing}. Run sm.update() or check the tickers.")
    first = r[tickers].apply(lambda s: s.first_valid_index())
    R = r[tickers].dropna()
    if len(R) < 120:
        raise ValueError(f"Only {len(R)} common days. {first.idxmax()} only starts {first.max().date()}; "
                         f"move START later or drop it.")
    if first.max() > pd.Timestamp(px.index[0]) + pd.Timedelta(days=10):
        print(f"Note: the shortest history is {first.idxmax()} (starts {first.max().date()}), so the window "
              f"used is {R.index[0].date()} to {R.index[-1].date()}.")
    return R, R.mean().values * TD, R.cov().values * TD, rf.reindex(R.index).mean() * TD


def _port(w, mu, cov, rfa):
    r = w @ mu
    v = np.sqrt(w @ cov @ w)
    return r, v, (r - rfa) / v


def _bounds(n):
    cap = max(MAX_W, 1.0 / n + 1e-6)
    return [(0.0, cap)] * n


def _frontier(mu, cov, n_pts=40):
    n = len(mu)
    b, cons = _bounds(n), {"type": "eq", "fun": lambda w: w.sum() - 1}
    x0 = np.ones(n) / n
    wmin = minimize(lambda w: w @ cov @ w, x0, bounds=b, constraints=cons).x
    wmax = minimize(lambda w: -w @ mu, x0, bounds=b, constraints=cons).x
    vols, rets, prev = [], [], wmin
    for tr in np.linspace(wmin @ mu, wmax @ mu, n_pts):
        s = minimize(lambda w: w @ cov @ w, prev, bounds=b, method="SLSQP",
                     constraints=[cons, {"type": "eq", "fun": lambda w, tr=tr: w @ mu - tr}])
        if s.success:
            prev = s.x
            vols.append(np.sqrt(s.x @ cov @ s.x)); rets.append(tr)
    return np.array(vols), np.array(rets)


def optimize(px, tickers=None, show=True, label="portfolio"):
    """Max-Sharpe, minimum-variance, risk-parity and equal-weight portfolios, plus the efficient frontier."""
    tickers = tickers or universe()
    R, mu, cov, rfa = _inputs(px, tickers)
    n = len(tickers)
    b, cons, x0 = _bounds(n), {"type": "eq", "fun": lambda w: w.sum() - 1}, np.ones(n) / n
    sols = {"max_sharpe": minimize(lambda w: -_port(w, mu, cov, rfa)[2], x0, bounds=b, constraints=cons).x,
            "min_variance": minimize(lambda w: w @ cov @ w, x0, bounds=b, constraints=cons).x,
            "risk_parity": minimize(lambda w: np.sum((w * (cov @ w) / (w @ cov @ w) - 1 / n) ** 2), x0,
                                    bounds=[(1e-4, 1)] * n, constraints=cons).x,
            "equal_weight": x0,
            "CHOSEN (actual weights)": chosen_weights(tickers).values}
    W = pd.DataFrame(sols, index=tickers).T
    perf = pd.DataFrame({k: _port(v, mu, cov, rfa) for k, v in sols.items()}, index=["exp_return", "vol", "sharpe"]).T
    print(f"=== {label}: optimal weights ({R.index[0].date()} to {R.index[-1].date()}, max {max(MAX_W, 1 / n):.0%} per ETF, long-only) ===")
    print((W * 100).round(1).to_string())
    print("\nIn-sample results (the optimizer saw this data, so these look better than real life):")
    print(perf.round(3).to_string())
    res = dict(weights=W, perf=perf, tickers=tickers, mu=mu, cov=cov, rfa=rfa, R=R)
    if show:
        plot_frontier(res)
        plot_weights(W, f"{label}: weights by method (%)")
    return res


