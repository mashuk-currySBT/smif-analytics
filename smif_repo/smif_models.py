def _read_positions(xlsx):
    raw = pd.read_excel(xlsx, header=None)
    h = raw.index[raw[1] == "Ticker"][0]
    df = raw.iloc[h + 1:, 1:11].copy()
    df.columns = ["ticker", "name", "qty", "w1", "w0", "ret", "v1", "v0", "p1", "p0"]
    df = df[df.ticker.notna() & ~df.ticker.astype(str).str.startswith("Portfolio Holdings")]
    for c in df.columns[2:]:
        df[c] = pd.to_numeric(df[c], errors="coerce")
    etf = df[df.ticker.isin(OWNED)].copy()
    stk = df[~df.ticker.isin(OWNED) & ~df.ticker.astype(str).str.startswith("Portfolio") & df.v0.notna()].copy()
    return etf, stk


