def load_holdings():
    h = pd.read_csv(os.path.join(DATA, "holdings.csv"))
    h["etf"] = h["etf"].str.upper().str.strip()
    h["ticker"] = h["ticker"].astype(str).str.strip()
    return h


def _download(tickers, start):
    import yfinance as yf
    parts = []
    for i in range(0, len(tickers), 40):
        chunk = tickers[i:i + 40]
        d = yf.download(chunk, start=start, auto_adjust=True, progress=False, threads=True)["Close"]
        if isinstance(d, pd.Series):
            d = d.to_frame(chunk[0])
        parts.append(d)
    px = pd.concat(parts, axis=1)
    px.index = pd.to_datetime(px.index).tz_localize(None)
    return px


def update():
    """Download (or refresh) all prices into data/prices.csv. Run when you want newer data."""
    h = load_holdings()
    etfs = sorted(set(OWNED) | set(CANDIDATES) | {MARKET} | set(FACTOR_ETFS) | set(h.etf))
    stocks = set(h.ticker[h.ticker != "REST"])
    try:
        _, stk = _read_positions(_smif_xlsx())
        stocks |= set(stk.ticker)
    except Exception as e:
        print("(no SMIF Excel file found; skipping its stocks)", e)
    stocks = sorted({_yf(s) for s in stocks} - set(etfs))
    print(f"Downloading {len(etfs)} ETFs from {DOWNLOAD_START} and {len(stocks)} stocks from {STOCK_START} ...")
    px_etf = _download(etfs, DOWNLOAD_START)
    px_stk = _download(stocks, STOCK_START)
    px = pd.concat([px_etf, px_stk], axis=1)
    px = px.loc[:, ~px.columns.duplicated()].dropna(how="all").sort_index()
    try:
        rf = pd.read_csv("https://fred.stlouisfed.org/graph/fredgraph.csv?id=DGS3MO",
                         index_col=0, parse_dates=True).iloc[:, 0]
        rf = pd.to_numeric(rf, errors="coerce") / 100
        px["RF"] = rf.reindex(px.index).ffill()
    except Exception as e:
        print("FRED unavailable, using fallback risk-free rate:", e)
        px["RF"] = RF_FALLBACK
    missing = [t for t in etfs + stocks if t not in px.columns or px[t].dropna().empty]
    px.to_csv(PRICES)
    print(f"Saved {px.shape[1]} series, {px.index[0].date()} to {px.index[-1].date()} -> {PRICES}")
    if missing:
        print("No data returned for:", missing, "(check the ticker spelling or try again later)")


def load(start=None, end=None, full=False):
    """Prices inside the modeling window (START/END). full=True returns everything downloaded."""
    if not os.path.exists(PRICES):
        raise FileNotFoundError("No data yet. Run  sm.update()  first.")
    px = pd.read_csv(PRICES, index_col=0, parse_dates=True).sort_index()
    if full:
        return px
    s, e = start or START, end or END
    if s:
        px = px[px.index >= pd.Timestamp(s)]
    if e:
        px = px[px.index <= pd.Timestamp(e)]
    if len(px) < 60:
        raise ValueError(f"Only {len(px)} days between {s} and {e}. Widen START/END "
                         f"(data covers {pd.read_csv(PRICES, index_col=0, parse_dates=True).index[[0, -1]].date.tolist()}).")
    return px


def split(px):
    """Daily log returns and daily risk-free rate."""
    rf = px["RF"].ffill().fillna(RF_FALLBACK) / TD if "RF" in px else pd.Series(RF_FALLBACK / TD, index=px.index)
    assets = px.drop(columns="RF", errors="ignore")
    r = np.log(assets / assets.shift(1))
    return r, rf.reindex(r.index).ffill()


