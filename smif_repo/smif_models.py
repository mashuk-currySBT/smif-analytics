def candidates(px, plot=True):
    """What happens to the portfolio if we move ADD_SIZE (e.g. 10%) of it into each candidate?"""
    r, rf = split(px)
    cur = OWNED
    w0 = chosen_weights(cur).values
    rows = {}
    for c in CANDIDATES:
        if c not in r.columns:
            print(f"skip {c}: no data"); continue
        D = r[cur + [c]].dropna()
        if len(D) < 120:
            print(f"skip {c}: only {len(D)} days in the window"); continue
        mu, cov = D.mean().values * TD, D.cov().values * TD
        rfa = rf.reindex(D.index).mean() * TD
        b0 = _port(np.append(w0, 0), mu, cov, rfa)
        b1 = _port(np.append(w0 * (1 - ADD_SIZE), ADD_SIZE), mu, cov, rfa)
        pr = D[cur] @ w0
        cc = D[cur].corrwith(D[c])
        X = np.column_stack([np.ones(len(D)), D[cur].values])
        beta, *_ = np.linalg.lstsq(X, D[c].values, rcond=None)
        r2 = 1 - ((D[c].values - X @ beta).var() / D[c].var())
        rows[c] = {"label": CANDIDATES[c], "days": len(D), "corr_w_portfolio": np.corrcoef(pr, D[c])[0, 1],
                   "most_similar": cc.idxmax(), "max_corr": cc.max(), "R2_by_holdings": r2,
                   "d_vol": b1[1] - b0[1], "d_exp_return": b1[0] - b0[0], "d_sharpe": b1[2] - b0[2]}
    out = pd.DataFrame(rows).T.sort_values("d_vol")
    print(f"=== Move {ADD_SIZE:.0%} of the portfolio into each candidate (taken pro-rata from our ETFs) ===")
    print("Trust d_vol and the correlations most; d_exp_return and d_sharpe depend on noisy past averages.")
    print(out.to_string(float_format=lambda x: f"{x:.3f}"))
    if plot and len(out):
        plt = _plt()
        fig, ax = plt.subplots(1, 2, figsize=(12, 4))
        ax[0].barh(out.index, out.corr_w_portfolio.astype(float), color=[_color(i) for i in out.index])
        ax[0].set_title("Correlation with our portfolio (lower = more different)"); ax[0].set_xlim(0, 1)
        d = out.d_vol.astype(float) * 100
        ax[1].barh(out.index, d, color=["#2e8b57" if v < 0 else "#c0392b" for v in d])
        ax[1].axvline(0, color="k", lw=.8); ax[1].set_title(f"Change in portfolio volatility if we add {ADD_SIZE:.0%} (pct points)")
        fig.tight_layout(); plt.show()
    return out


